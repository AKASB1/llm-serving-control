"""Describe committed replay excerpts: request rate, token loads, length distributions,
timestamp resolution, and same-second arrivals (standard library only).

Usage:
    python scripts/trace_stats.py [--out docs/figures/replay-burstgpt/trace_stats.md]
                                  [--burstgpt-source outputs/real-traces/BurstGPT_1.csv]

Reads configs/traces/{azure-conv-300s,azure-code-600s,burstgpt-600s}.csv and their
manifests. With --burstgpt-source (the downloaded release file, not committed), it also
counts the models and log types of the source rows in the BurstGPT window. The numbers
describe the traffic only; the replay results are simulated.
"""
import argparse
import csv
import json
import os
from collections import Counter

EXCERPTS = ["azure-conv-300s", "azure-code-600s", "burstgpt-600s"]


def quantile(xs, q):
    """Nearest-rank quantile of a sorted list."""
    k = max(0, min(len(xs) - 1, int(-(-q * len(xs) // 1)) - 1))
    return xs[k]


def stats(name):
    path = os.path.join("configs", "traces", name + ".csv")
    with open(path, encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f))
    with open(os.path.join("configs", "traces", name + ".manifest.json"), encoding="utf-8") as f:
        man = json.load(f)
    dur = man["duration_s"]
    prompt = sorted(int(r["prompt_tokens"]) for r in rows)
    out = sorted(int(r["output_tokens"]) for r in rows)
    arr = [float(r["arrival_s"]) for r in rows]
    whole = all(a == int(a) for a in arr)
    per_instant = Counter(arr)
    per_second = Counter(int(a) for a in arr)
    return {
        "name": name, "requests": len(rows), "duration_s": dur, "rate": len(rows) / dur,
        "prompt_rate": sum(prompt) / dur, "output_rate": sum(out) / dur,
        "prompt": prompt, "output": out, "whole_seconds": whole,
        "instants": len(per_instant), "max_per_instant": max(per_instant.values()),
        "max_per_second": max(per_second.values()),
    }


def source_mix(path, start_s, dur_s):
    """Model x log type of the source rows in the window (failed rows included), and the same
    counts, the timestamp resolution, and the median non-zero output over the whole file."""
    window, whole = Counter(), Counter()
    outs, fractional, t0 = [], 0, None
    with open(path, encoding="utf-8", newline="") as f:
        for r in csv.DictReader(f):
            ts = float(r["Timestamp"])
            t0 = ts if t0 is None else t0
            key = (r["Model"], r["Log Type"])
            whole[key] += 1
            fractional += ts != int(ts)
            if int(r["Response tokens"]) > 0:
                outs.append(int(r["Response tokens"]))
            if start_s <= ts - t0 < start_s + dur_s:
                window[key] += 1
    outs.sort()
    return window, whole, fractional, quantile(outs, 0.5)


def dist(xs):
    return (f"{quantile(xs, 0.5)} / {quantile(xs, 0.9)} / {quantile(xs, 0.99)} / {xs[-1]}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join("docs", "figures", "replay-burstgpt", "trace_stats.md"))
    ap.add_argument("--burstgpt-source", default="")
    a = ap.parse_args()
    S = [stats(n) for n in EXCERPTS]
    lines = ["<!-- generated by scripts/trace_stats.py from configs/traces/; do not edit by hand -->",
             "Traffic of the committed replay excerpts (real timestamps and token counts; every replay result built on them is simulated). "
             "Length columns: median / P90 / P99 / max, nearest rank.", "",
             "| excerpt | requests | duration (s) | requests/s | prompt tokens/s | output tokens/s | prompt tokens | output tokens | "
             "whole-second timestamps | distinct arrival instants | max arrivals at one instant | max arrivals in one second |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for s in S:
        lines.append(f"| `{s['name']}` | {s['requests']} | {s['duration_s']:g} | {s['rate']:.2f} | {s['prompt_rate']:.0f} | "
                     f"{s['output_rate']:.0f} | {dist(s['prompt'])} | {dist(s['output'])} | {'yes' if s['whole_seconds'] else 'no'} | "
                     f"{s['instants']} | {s['max_per_instant']} | {s['max_per_second']} |")
    if a.burstgpt_source:
        with open(os.path.join("configs", "traces", "burstgpt-600s.manifest.json"), encoding="utf-8") as f:
            p = json.load(f)["generator"]["params"]
        window, whole, fractional, med_out = source_mix(a.burstgpt_source, p["start_s"], p["duration_s"])
        nw, nf = sum(window.values()), sum(whole.values())
        lines += ["", f"Source rows of `{p['source']}` (not committed): the BurstGPT window (start {p['start_s']:.0f} s after the first "
                  f"request, {p['duration_s']:g} s, {nw} rows including {p['stats']['Dropped']} failed ones) against the whole file "
                  f"({nf} rows). Timestamps with a fractional part in the whole file: {fractional}. Median non-zero output over the "
                  f"whole file: {med_out} tokens.", "",
                  "| model | log type | rows in the window | share of the window | rows in the file | share of the file |", "|---|---|---|---|---|---|"]
        for key in sorted(whole, key=lambda k: (-window[k], k)):
            lines.append(f"| `{key[0]}` | `{key[1]}` | {window[key]} | {100 * window[key] / nw:.1f} % | {whole[key]} | "
                         f"{100 * whole[key] / nf:.1f} % |")
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
