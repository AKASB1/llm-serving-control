"""Write the reweighting tables from committed results (standard library only).

Usage:
    python scripts/reweight_tables.py [--results benchmarks/results-reweight] [--out docs/figures/reweight]

Reads rankings.csv, summary.csv, gpu_cap.csv, and manifest.json written by
`go run ./cmd/benchmark -reweight configs/reweight.json`; writes results_table.md
and updates the README block between <!-- reweight-summary:start --> and
<!-- reweight-summary:end --> in benchmarks/README.md. Every number comes from
those files. The per-run metrics behind them are simulated with assumed parameters.
"""
import argparse
import csv
import json
import os
from collections import OrderedDict

VERDICT = {"better": "✓", "worse": "✗", "no_difference": "="}
HEADER = "<!-- generated by scripts/reweight_tables.py from benchmarks/results-reweight; do not edit by hand -->"


def read(path):
    with open(path, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def weights_of(rows):
    out = OrderedDict()
    for r in rows:
        out.setdefault(r["weights"], "/".join(r[k] for k in ("alpha", "beta", "gamma", "delta")))
    return out


def full_table(rank, summ, gcap, man, ref):
    ws = weights_of(rank)
    lines = [HEADER,
             f"Recomputed from `{man['runs']}` (variant `{man['variant']}`, {man['rows']} runs; SHA-256 `{man['runs_sha256'][:12]}`) "
             f"with `{man['reweight_config']}` at commit `{man['commit'][:7]}`. No run was repeated and nothing was re-tuned: "
             "the frozen configurations keep the parameters tuned under the reference weights. "
             "J' = α·j_ttft + β·j_tpot + γ·j_gpu + δ·violation_rate. Cell: rank among the non-oracle policies "
             "(1 = lowest mean J') and the paired verdict against the family baseline (✓ better, ✗ worse, = no difference). "
             "Simulated, assumed parameters.", "",
             "| weights | α/β/γ/δ |", "|---|---|"] + [f"| `{w}` | {v} |" for w, v in ws.items()] + [""]
    by = OrderedDict()
    for r in rank:
        by.setdefault((r["scenario"], r["family"], r["policy"]), {})[r["weights"]] = r
    scen = OrderedDict()
    for (sc, fam, p) in by:
        scen.setdefault((sc, fam), []).append(p)
    for (sc, fam), pols in scen.items():
        base = by[(sc, fam, pols[0])][ref]["baseline"]
        lines += [f"**{sc}** ({fam}, baseline `{base}`)", "",
                  "| policy | " + " | ".join(f"`{w}`" for w in ws) + " |", "|---|" + "---|" * len(ws)]
        for p in pols:
            cells = []
            for w in ws:
                r = by[(sc, fam, p)][w]
                if r["oracle"] == "true":
                    cells.append("ref " + VERDICT.get(r["verdict"], ""))
                elif p == base:
                    cells.append(f"{r['rank']} (baseline)")
                else:
                    cells.append(f"{r['rank']} {VERDICT.get(r['verdict'], '')}".strip())
            name = p + (" (oracle)" if by[(sc, fam, p)][ref]["oracle"] == "true" else "")
            lines.append(f"| {name} | " + " | ".join(cells) + " |")
        lines.append("")
    lines += ["**Ranking agreement with the reference weights**", "",
              "| weights | scenario | Kendall τ | top policy | top policy (reference) | verdicts unchanged |", "|---|---|---|---|---|---|"]
    for r in summ:
        if r["weights"] == ref:
            continue
        lines.append(f"| `{r['weights']}` | {r['scenario']} | {r['kendall_tau_vs_reference']} | `{r['top_policy']}` | "
                     f"`{r['top_policy_reference']}` | {r['verdicts_same']} of {r['verdicts_total']} |")
    lines += [""] + gpu_cap_table(gcap)
    return "\n".join(lines) + "\n"


def gpu_cap_table(gcap):
    if not gcap:
        return []
    w = gcap[0]["weights"]
    lines = [f"**GPU-hours cap** (scaling family): a policy is feasible if its mean GPU-hours are at most the baseline's "
             f"in that scenario; feasible non-oracle policies are ranked by mean J' under `{w}`. Oracles are shown, not ranked.", "",
             "| scenario | policy | mean GPU-h | cap GPU-h | feasible | mean J' | rank |", "|---|---|---|---|---|---|---|"]
    for r in gcap:
        name = r["policy"] + (" (oracle)" if r["oracle"] == "true" else "")
        lines.append(f"| {r['scenario']} | {name} | {r['mean_gpu_hours']} | {r['cap_gpu_hours']} | {r['feasible']} | "
                     f"{r['mean_J']} ± {r['ci95']} | {r['rank']} |")
    return lines + [""]


def summary_block(summ, ref):
    ws = OrderedDict()
    for r in summ:
        if r["weights"] != ref:
            ws.setdefault(r["weights"], []).append(r)
    n = len({r["scenario"] for r in summ})
    lines = [HEADER,
             f"Per weight vector, over the {n} base scenarios: scenarios whose top non-oracle policy is the same as under the "
             f"reference weights `{ref}`, the range of Kendall τ against the reference ranking, and the verdicts against the "
             "family baseline that stay the same. Recomputed from the committed per-run metrics; simulated, assumed parameters.", "",
             "| weights | same top policy | Kendall τ (min, max) | verdicts unchanged | top policy changes in |", "|---|---|---|---|---|"]
    for w, rows in ws.items():
        same = sum(r["top_same"] == "true" for r in rows)
        taus = [r["kendall_tau_vs_reference"] for r in rows]
        vs, vt = sum(int(r["verdicts_same"]) for r in rows), sum(int(r["verdicts_total"]) for r in rows)
        lo = min(taus, key=float)
        hi = max(taus, key=float)
        changed = ", ".join(r["scenario"] for r in rows if r["top_same"] != "true") or "none"
        lines.append(f"| `{w}` | {same} of {len(rows)} | {lo}, {hi} | {vs} of {vt} | {changed} |")
    return "\n".join(lines) + "\n"


def splice(path, marker, content):
    """Replace the text between <!-- marker:start --> and <!-- marker:end -->."""
    if not os.path.exists(path):
        return
    text = open(path, encoding="utf-8").read()
    start, end = f"<!-- {marker}:start -->", f"<!-- {marker}:end -->"
    if start not in text or end not in text:
        return
    a, b = text.index(start) + len(start), text.index(end)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text[:a] + "\n" + content.rstrip("\n") + "\n" + text[b:])
    print(f"updated {path} [{marker}]")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="benchmarks/results-reweight")
    ap.add_argument("--out", default="docs/figures/reweight")
    ap.add_argument("--no-splice", action="store_true", help="do not update the README block")
    args = ap.parse_args()
    rank = read(os.path.join(args.results, "rankings.csv"))
    summ = read(os.path.join(args.results, "summary.csv"))
    gcap = read(os.path.join(args.results, "gpu_cap.csv"))
    with open(os.path.join(args.results, "manifest.json"), encoding="utf-8") as f:
        man = json.load(f)
    ref = rank[0]["weights"]
    os.makedirs(args.out, exist_ok=True)
    path = os.path.join(args.out, "results_table.md")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(full_table(rank, summ, gcap, man, ref))
    print(f"wrote {path}")
    if not args.no_splice:
        splice(os.path.join("benchmarks", "README.md"), "reweight-summary", summary_block(summ, ref))


if __name__ == "__main__":
    main()
